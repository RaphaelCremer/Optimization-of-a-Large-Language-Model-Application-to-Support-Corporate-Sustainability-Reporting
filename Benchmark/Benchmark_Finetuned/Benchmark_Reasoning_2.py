#Benchmarking the reasoning SFT model on ESGenius with forced multiple choice answer format
#Adapted and modified from Muennighoff, N, Yang, Z, Shi, W, Li, XL, Fei-Fei, L, Hajishirzi, H, Zettlemoyer, L, Liang, P, Candès, E & Hashimoto, T 2025, s1: Simple test-time scaling. Available from: https://github.com/simplescaling/s1 [19. September 2026] under Apache License Version 2.0, January 2004 found under /Third_Party_Licenses
#ESGenius Prompt adapted from He, C, Zhou, X, Wu, Y, Yu, X, Zhang, Y, Zhang, L, Di Wang, Lyu, S, Xu, H, Wang, X, Liu, W & Miao, C 2025, ESGenius: Benchmarking LLMs on Environmental, Social, and Governance (ESG) and Sustainability Knowledge, Available from: https://github.com/ANGEL-NTU/ESGenius [27 October 2026] under Apache License Version 2.0, January 2004 found under /Third_Party_Licenses

from vllm import LLM, SamplingParams
from transformers import AutoTokenizer
import json


def save_results(results, json_path):
    with open(json_path, "w", encoding="utf-8") as file:
        json.dump(results, file, ensure_ascii=False, indent=2)


Model = "/hpcwork/x/qwen_Training_Data_final_reasoning_trace.json_bs16_lr1e-5_epoch5_wd1e-4_20260905-140040.out"

ESGenius = "Benchmark/ESGenius/ESGenius_1136q.json"
ESGenius_output = "Benchmark/ESGenius/ESGenius_BFSFT_2.json"

Answer_options = ("A", "B", "C", "D", "Z")

#ESGenius Prompt
System_prompt_ESGenius = (
    "You are answering a multiple-choice ESG benchmark question. "
    "Select the single best option from A, B, C, D, or Z. "
    "Return only the option letter and no explanation."
)

User_prompt_template_ESGenius = """[Question text]
{question}

[Option A text]
{option_a}

[Option B text]
{option_b}

[Option C text]
{option_c}

[Option D text]
{option_d}

[Option Z text]
{option_z}
"""

#Assign model path, gpu and tokenizer
model = LLM(
    Model,
    tensor_parallel_size=1,
    enable_prefix_caching=True,
    gpu_memory_utilization=0.90,
)
tokenizer = AutoTokenizer.from_pretrained(Model)

im_start_id = tokenizer.convert_tokens_to_ids("<|im_start|>")
im_end_id = tokenizer.convert_tokens_to_ids("<|im_end|>")
choice_token_ids = [
    tokenizer.encode(choice, add_special_tokens=False)[0]
    for choice in Answer_options
]

with open(ESGenius, "r", encoding="utf-8") as file:
    esgenius_tasks = json.load(file)

esgenius_prompts = []
for task in esgenius_tasks:
    user_prompt = User_prompt_template_ESGenius.format(
        question=task["question"],
        option_a=task["options"]["A"],
        option_b=task["options"]["B"],
        option_c=task["options"]["C"],
        option_d=task["options"]["D"],
        option_z=task["options"]["Z"],
    )
    esgenius_prompts.append(user_prompt)

#Generation of reasoning trace
esgenius_model_prompts = []
for task, p in zip(esgenius_tasks, esgenius_prompts):
    prompt = "<|im_start|>system\n" + System_prompt_ESGenius + "<|im_end|>\n<|im_start|>user\n" + p + "<|im_end|>\n<|im_start|>assistant\n"
    prompt += "<|im_start|>think"
    esgenius_model_prompts.append(prompt)

stop_token_ids = [im_start_id, im_end_id]
sampling_params = SamplingParams(
    max_tokens=2048,
    min_tokens=0,
    stop_token_ids=stop_token_ids,
    skip_special_tokens=False,
    temperature=0.0,
)
o = model.generate(
    esgenius_model_prompts,
    sampling_params=sampling_params,
)
### Final answer ###

#Inject **Final Answer** if not generated by the model
esgenius_reasoning = []
for request_output in o:
    reasoning = request_output.outputs[0].text.rstrip()
    if not reasoning.endswith("**Final Answer**"):
        reasoning += "\n**Final Answer**"
    esgenius_reasoning.append(reasoning)

esgenius_model_prompts = [
    prompt + reasoning + "\n<|im_start|>answer\n"
    for prompt, reasoning in zip(esgenius_model_prompts, esgenius_reasoning)
]

#For the final answer only A, B, C, D, Z is allowed
sampling_params = SamplingParams(
    max_tokens=1,
    min_tokens=1,
    allowed_token_ids=choice_token_ids,
    skip_special_tokens=False,
    temperature=0.0,
)
o = model.generate(
    esgenius_model_prompts,
    sampling_params=sampling_params,
)

results = []
for task, request_output, reasoning in zip(esgenius_tasks, o,esgenius_reasoning,):
    answer = request_output.outputs[0].text.strip().upper()
    result = dict(task)
    result["attempt"] = answer
    result["reasoning"] = reasoning
    results.append(result)

save_results(
    results,
    ESGenius_output,
)
